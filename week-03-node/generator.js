// inserting file system
const fs = require('fs');

// stores arguments after index 2
const args = process.argv.slice(2);

if (args[0] !== undefined) {
    // convert arg to number
    const fileCount = Number(args[0]);

    // !Number.isNaN(fileCount) what i could've used before but only checking NaN
    if (0 < fileCount && Number.isInteger(fileCount)) {
        const fileNameType = args[1];

        if (args[1] !== undefined) {
            if (checkValidFileName(fileNameType)) {
                try {

                    for (let i = 1; i <= fileCount; i++) {
                        // wx flag - Open file for writing. The file is created 
                        // (if it does not exist)but fails if the path exists
                        fs.writeFileSync(`${fileNameType}-${i}.txt`, `File: ${fileNameType}-${i}\nGenerated by Node.js`,{flag:'wx'});
                        console.log(`Created txt file: ${i}`);
                    }
                }
                catch (e) {
                    console.log(`ERROR: ${e.path} - ${e.code}`);
                }
            }
            else{
                console.log("ERROR: File Name Type: Cannot contain '/' or '\\'");
            }
        }
        else {
            console.log("ERROR: Command-line is missing File Name Type");
        }
    }
    else {
        console.log("ERROR: File Count must be greater than 0 and a valid whole number");
    }
}
else {
    console.log("ERROR: Command-line is missing arguments");
}

function checkValidFileName(fName) {
    for (const char of fName) {
        // char === "\" causes a syntax error 
        // because the backslash escapes the closing quote mark, 
        // leaving the string open
        if (char === '/' || char === '\\') {
            return false;
        }
    }
    return true;
}